-- =============================================================================
-- キーマップ設定
-- =============================================================================
-- プラグイン固有のキーマップは各プラグインのファイルで定義している。
-- LSP 関連のキーマップは lua/lang/_loader.lua の on_attach() で定義している。
-- ここではプラグインに依存しない汎用キーマップのみ管理する。
-- =============================================================================

local map  = vim.keymap.set
local opts = { noremap = true, silent = true }

-- Leader キー（スペース）
-- <leader>xxx 形式のキーマップはすべてこのキーを起点にする
vim.g.mapleader = " "

-----------------------------------------------------
-- ファイル操作
-----------------------------------------------------
map("n", "<leader>w", ":w<CR>",  opts) -- 上書き保存
map("n", "<leader>x", ":wq<CR>", opts) -- 保存して終了（注: code_runner の <leader>x と競合注意）
map("n", "<leader>q", ":q<CR>",  opts) -- 終了（未保存の変更があれば警告）
map("n", "<leader>Q", ":q!<CR>", opts) -- 強制終了（未保存の変更を破棄）

-----------------------------------------------------
-- ウィンドウ移動
-----------------------------------------------------
-- <C-w>h/j/k/l の短縮版。分割ウィンドウ間を素早く移動する
map("n", "<leader>h", "<C-w>h", opts) -- 左のウィンドウへ
map("n", "<leader>j", "<C-w>j", opts) -- 下のウィンドウへ
map("n", "<leader>k", "<C-w>k", opts) -- 上のウィンドウへ
map("n", "<leader>l", "<C-w>l", opts) -- 右のウィンドウへ

-- ウィンドウのリサイズ（Ctrl + 矢印キー）
map("n", "<C-Up>",    ":resize -2<CR>",          opts) -- 高さを縮める
map("n", "<C-Down>",  ":resize +2<CR>",           opts) -- 高さを広げる
map("n", "<C-Left>",  ":vertical resize -2<CR>",  opts) -- 幅を縮める
map("n", "<C-Right>", ":vertical resize +2<CR>",  opts) -- 幅を広げる

-----------------------------------------------------
-- 削除をヤンクしない
-----------------------------------------------------
-- デフォルトの d / D / x はヤンクレジスタ（"）にも入る。
-- "_d にすることでブラックホールレジスタに捨て、ヤンクが上書きされなくなる。
-- → yy でコピーした後に dd しても貼り付け内容が変わらない
map({ "n", "x" }, "d", '"_d',  opts)
map({ "n", "x" }, "D", '"_D',  opts)
map("n",          "x", '"_x',  opts) -- 1 文字削除もヤンクしない
map("x",          "p", '"_dP', opts) -- ビジュアル貼り付けで元のヤンクを保持

-----------------------------------------------------
-- 移動を画面行ベースに変更
-----------------------------------------------------
-- 折り返しのある長い行で j / k が視覚的な 1 行ずつ動くようになる。
-- 元の論理行移動は gj / gk に置き換える。
map("n", "j",  "gj", opts)
map("n", "k",  "gk", opts)
map("n", "gj", "j",  opts)
map("n", "gk", "k",  opts)

-----------------------------------------------------
-- 行頭・行末の移動を Shift+H / L に割り当て
-----------------------------------------------------
-- ^ / $ の代わりに使う（押しやすいキーで行頭・行末に飛ぶ）
map("v", "<S-h>", "^", opts) -- ビジュアル: 行頭（空白を除いた最初の文字）
map("v", "<S-l>", "$", opts) -- ビジュアル: 行末
map("n", "<S-h>", "^", opts) -- ノーマル: 行頭
map("n", "<S-l>", "$", opts) -- ノーマル: 行末

-----------------------------------------------------
-- インサートモードの脱出
-----------------------------------------------------
map("i", "jj",  "<Esc>", opts) -- ホームポジションのまま Esc できる
map("i", "<C-c>", "<Esc>", opts) -- Ctrl+C でも Esc 相当に（デフォルトと同動作）
