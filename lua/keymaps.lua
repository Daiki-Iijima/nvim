-- =============================================================================
-- キーマップ設定
-- =============================================================================
-- プラグイン固有のキーマップは各プラグインのファイルで定義している。
-- LSP 関連のキーマップは lua/lang/_loader.lua の on_attach() で定義している。
-- ここではプラグインに依存しない汎用キーマップのみ管理する。
-- =============================================================================

local map  = vim.keymap.set
local opts = { noremap = true, silent = true }

-- Leader / Local Leader キー
-- <leader>xxx 形式はスペース、<localleader>xxx 形式はカンマを起点にする
vim.g.mapleader = " "
vim.g.maplocalleader = ","

-----------------------------------------------------
-- ファイル操作
-----------------------------------------------------
-- <leader>wq は <leader>w と頭が重なる（<leader>w が待たされる）ので外した。保存して終了は :wq か ZZ
map("n", "<leader>w", ":w<CR>",  vim.tbl_extend("force", opts, { desc = "保存" }))
map("n", "<leader>q", ":q<CR>",  vim.tbl_extend("force", opts, { desc = "閉じる" })) -- 未保存の変更があれば警告
map("n", "<leader>Q", ":q!<CR>", vim.tbl_extend("force", opts, { desc = "保存せず閉じる" }))

-----------------------------------------------------
-- ウィンドウ移動
-----------------------------------------------------
-- <C-h>/<C-j>/<C-k>/<C-l>（vim-tmux-navigator）を使う。<leader>h/j/k/l は同じ動きの重複なので外した

-- ウィンドウのリサイズ（Ctrl + 矢印キー）
map("n", "<C-Up>",    ":resize -2<CR>",          opts) -- 高さを縮める
map("n", "<C-Down>",  ":resize +2<CR>",           opts) -- 高さを広げる
map("n", "<C-Left>",  ":vertical resize -2<CR>",  opts) -- 幅を縮める
map("n", "<C-Right>", ":vertical resize +2<CR>",  opts) -- 幅を広げる

-----------------------------------------------------
-- 削除をヤンクしない
-----------------------------------------------------
-- デフォルトの d / D / x はヤンクレジスタ（"）にも入る。
-- "_d にすることでブラックホールレジスタに捨て、ヤンクが上書きされなくなる。
-- → yy でコピーした後に dd しても貼り付け内容が変わらない
map({ "n", "x" }, "d", '"_d',  opts)
map({ "n", "x" }, "D", '"_D',  opts)
map("n",          "x", '"_x',  opts) -- 1 文字削除もヤンクしない

-----------------------------------------------------
-- 移動を画面行ベースに変更
-----------------------------------------------------
-- 折り返しのある長い行で j / k が視覚的な 1 行ずつ動くようになる。
-- 元の論理行移動は gj / gk に置き換える。
map("n", "j",  "gj", opts)
map("n", "k",  "gk", opts)
map("n", "gj", "j",  opts)
map("n", "gk", "k",  opts)

-----------------------------------------------------
-- 行頭・行末の移動を Shift+H / L に割り当て
-----------------------------------------------------
-- ^ / $ の代わりに使う（押しやすいキーで行頭・行末に飛ぶ）
map("v", "<S-h>", "^", opts) -- ビジュアル: 行頭（空白を除いた最初の文字）
map("v", "<S-l>", "$", opts) -- ビジュアル: 行末
map("n", "<S-h>", "^", opts) -- ノーマル: 行頭
map("n", "<S-l>", "$", opts) -- ノーマル: 行末

-----------------------------------------------------
-- インサートモードの脱出
-----------------------------------------------------
map("i", "jj",  "<Esc>", opts) -- ホームポジションのまま Esc できる
map("i", "<C-c>", "<Esc>", opts) -- Ctrl+C でも Esc 相当に（デフォルトと同動作）

-----------------------------------------------------
-- コメントアウト (Neovim 0.10+ 内蔵機能)
-----------------------------------------------------
-- Ctrl + / (ターミナル上は <C-_> として入力される) でコメントをトグル (VSCode風)
map("n", "<C-_>", "gcc", { remap = true, silent = true, desc = "コメントアウトをトグル" })
map("v", "<C-_>", "gc",  { remap = true, silent = true, desc = "コメントアウトをトグル" })

-----------------------------------------------------
-- 検索
-----------------------------------------------------
-- * / # は単語を検索するが、カーソルは動かさない（件数 [3/12] は Neovim 組み込みで出る）
map("n", "*", "*N", opts)
map("n", "#", "#N", opts)
map("n", "<Esc><Esc>", "<Cmd>noh<CR>", opts) -- 検索ハイライトを消す
