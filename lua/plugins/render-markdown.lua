-- =============================================================================
-- render-markdown.nvim: Markdown のリッチレンダリング
-- =============================================================================
-- Markdown ファイルをそのまま Neovim 上で視覚的に整形表示する。
-- 実際のファイル内容は変えず、画面描画だけを装飾する。
--
-- 主な視覚効果:
--   見出し  → レベルごとに異なるアイコンと色で表示（H1〜H6）
--   コードブロック → 背景色付きで表示、言語名も色分け
--   リスト  → 階層に応じてアイコンを変える（●○◆◇）
--   テーブル → 罫線を整列表示
--   チェックボックス → [ ] / [x] をアイコンで表示
--
-- 依存:
--   nvim-treesitter → Markdown の構文解析に使用
--   nvim-web-devicons → 言語アイコンの表示に使用
-- =============================================================================

return {
  "MeanderingProgrammer/render-markdown.nvim",
  ft = { "markdown" }, -- Markdown ファイルを開いたときだけ読み込む
  dependencies = {
    "nvim-treesitter/nvim-treesitter",
    "nvim-tree/nvim-web-devicons",
  },
  opts = {
    sign = { enabled = false }, -- サインカラムへのアイコン表示を無効化（バッファ内に既に表示されるため冗長）
    yaml = { enabled = false }, -- YAML コードブロック内の - をbulletとしてレンダリングしない
    heading = {
      -- アイコンなし・背景色のみで見出しレベルを表現
      icons = {},
      sign = false,
    },
    code = {
      enabled  = true,   -- コードブロックの装飾を有効化
      style    = "full", -- "full" → 行全体に背景色を付ける（"normal" は左端のみ）
      left_pad = 1,      -- 言語アイコンの左に余白を追加（左端でのクリップを防ぐ）
    },
    bullet = {
      -- リストの階層ごとにアイコンを変える
      icons = { "●", "○", "◆", "◇" },
    },
  },
}
