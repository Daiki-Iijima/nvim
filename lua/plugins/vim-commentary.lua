-- =============================================================================
-- vim-commentary: コメントのトグル
-- =============================================================================
-- gcc / gc でコメントアウト・コメント解除を切り替える。
-- ファイルタイプに応じたコメント記号を自動で判断する。
--   Lua   → --
--   JS/TS → //
--   HTML  → <!-- -->
--   Python → #  など
--
-- キーマップ（このファイルで定義）:
--   <C-_>（Ctrl + /）→ 現在行をコメントトグル（VSCode と同じ操作感）
--   ビジュアル選択中に <C-_> → 選択範囲をコメントトグル
-- =============================================================================

return {
  "tpope/vim-commentary",
  event = "VeryLazy", -- 起動後の最初の操作まで読み込みを遅らせる

  config = function()
    -- Ctrl + / でコメントトグル（VSCode 風）
    vim.keymap.set("n", "<C-_>", "gcc", { noremap = true, silent = true })
    vim.keymap.set("v", "<C-_>", "gc",  { noremap = true, silent = true })
  end,
}
