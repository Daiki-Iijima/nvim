-- =============================================================================
-- lazydev.nvim: Neovim Lua 開発環境の強化
-- =============================================================================
-- Lua ファイルを編集するときに Neovim の API 型情報を lua_ls に自動で提供する。
--
-- これがないと:
--   ・vim.api / vim.lsp / vim.fn などが "Undefined global `vim`" と警告される
--   ・vim.api.nvim_* 系の関数で補完・型チェックが効かない
--
-- これがあると:
--   ・vim グローバルの警告が消える
--   ・nvim_buf_get_lines() などの引数の型や戻り値が補完される
--   ・補完候補に lazydev ソース（Neovim 標準 API）が最優先で表示される
--
-- library:
--   vim.uv → libuv バインディング（非同期ファイル操作など）の型情報を追加
-- =============================================================================

return {
  {
    "folke/lazydev.nvim",
    ft = "lua", -- Lua ファイルを開いたときだけ読み込む
    opts = {
      library = {
        -- vim.uv（非同期 I/O）の型情報を追加
        { path = "${3rd}/luv/library", words = { "vim%.uv" } },
      },
    },
  },
}
