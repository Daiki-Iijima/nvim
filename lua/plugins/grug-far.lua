-- =============================================================================
-- grug-far.nvim: 直感的で強力なプロジェクト内一括置換
-- =============================================================================
-- 単一のバッファの中で、検索ワードと置換ワードを入力し、
-- 保存 (:w) するだけでプロジェクト全体の複数ファイルを一括置換できます。
-- =============================================================================

return {
  "MagicDuck/grug-far.nvim",
  cmd = "GrugFar",
  opts = {
    keymaps = {
      replace = { n = "<leader>r", i = "<C-Enter>" },
      syncLocations = { n = "<leader>s", i = "<C-s>" },
    },
  },
  keys = {
    {
      "<leader>sr",
      "<cmd>GrugFar<cr>",
      desc = "GrugFar: プロジェクト内一括置換を開く",
    },
  },
}
